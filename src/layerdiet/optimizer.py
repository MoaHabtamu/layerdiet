"""Generates optimized multi-stage Dockerfiles with minimal runtime footprint."""


class DockerOptimizer:
    @staticmethod
    def generate_slim_dockerfile(python_version: str = "3.11", entrypoint_cmd: str = 'python -m app') -> str:
        return f"""# Generated by LayerDiet (Optimized Multi-Stage Build)

# Stage 1: Build & Dependencies Builder
FROM python:{python_version}-slim AS builder

WORKDIR /app

RUN apt-get update && apt-get install -y --no-install-recommends \\
    build-essential \\
    && rm -rf /var/lib/apt/lists/*

COPY requirements.txt .
RUN pip install --no-cache-dir --prefix=/install -r requirements.txt

# Stage 2: Minimal Runtime
FROM python:{python_version}-slim AS runner

WORKDIR /app

# Non-root security user
RUN groupadd -g 1000 appuser && useradd -u 1000 -g appuser -s /bin/sh appuser

COPY --from=builder /install /usr/local
COPY . /app

USER appuser

EXPOSE 8000
CMD [{entrypoint_cmd}]
"""
